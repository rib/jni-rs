///
/// # Usage
///
/// `_with_native_trait_state! { $all_props, $cb, $type, $native_methods, [extra...] }`
///
/// Calls `$cb! { $all_props, $native_trait, $native_trait_impl, $native_error_policy, $native_methods, extra... }`
///
/// If `native_trait` is unset it defaults to `[< $type NativeInterface >]`
///
/// If `native_trait_impl` is unset it defaults to `[< $type NativeMethods >]`
///
/// If `native_error_policy` is unset it defaults to `$crate::errors::ThrowRuntimeExAndDefault`
