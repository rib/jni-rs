macro_rules! _foreach_impl_closure {
    ( $selector:ident, {$( $name:ident = $closure:tt ),*}, $callback:ident, $fallback:ident, $extra:tt ) => {
        //compile_error! { concat!("Foreach closures: ", stringify!($($name),*), ", callback = ", stringify!($callback), ", extra = ", stringify!($extra)) }
        {
            let mut selected: Option<_> = None;
            $(
                if let Some(ret) = _call_impl_closure_selector! { $selector, $name = $closure, $callback, $extra } {
                    selected = Some(ret);
                }
            )*

            match selected {
                Some(selected) => selected,
                None => {
                    //compile_error! { concat!("No closure selected, calling fallback: ", stringify!($fallback), ", extra = ", stringify!($extra)) }
                    // No closure matched, call the fallback
                    _call_fallback! { $fallback, $extra }
                }
            }
        }
    };
}

/// Expand all closures with a $selector to only call the $callback for a single closure
///
/// # Usage
///
/// _select_impl_closure! { $selector, { name = |args| { ... }, ... } }
///
/// Calls `$selector! { name = ( |args| { ... } )}` for each closure in the list
///
/// Note: The closure is wrapped in parentheses as a simplification so it can be matched as a single `:tt`.
macro_rules! _select_impl_closure {
    ( $selector:ident, { $( $name:ident = | $($arg:tt),* | $closure:tt ),* $(,)? }, $callback:ident, $fallback:ident $(, $($extra:tt)* )? ) => {
        //compile_error! { concat!("Selecting closures: ", stringify!($($name),*), ", callback = ", stringify!($callback)) }
        _foreach_impl_closure! {
            $selector, {$( $name = (| $($arg),* | $closure ) ),*}, $callback, $fallback, [ $(, $($extra)* )? ]
        }
    };
}

