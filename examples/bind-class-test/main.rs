#[macro_export]
macro_rules! _emit_alias_assignable_check {
    ( ($AsliasType:ident), $Type:ident, $class:expr, $env:expr, $loader_context:expr ) => {
        $crate::_emit_alias_assignable_check! { @emit $AsliasType, $Type, $class, $env, $loader_context }
    };
    ( ($stem:ident = $AsliasType:ident), $Type:ident, $class:expr, $env:expr, $loader_context:expr ) => {
        $crate::_emit_alias_assignable_check! { @emit $AsliasType, $Type, $class, $env, $loader_context }
    };
    (@emit $AliasType:ident, $Type:ident, $class:expr, $env:expr, $loader_context:expr ) => {{
        let alias_class = <$AliasType as $crate::refs::Reference>::lookup_class($env, $loader_context)?;
        // Safety: rust-analyzer, spuriously, thinks this is unsafe, even though it's not as rustc doesn't complain
        let alias_class: &JClass = unsafe { alias_class.as_ref() };
        // Safety: we know that class and alias_class are valid, non-null class references
        let is_assignable = unsafe { jni_call_unchecked!($env, v1_1, IsAssignableFrom, alias_class.as_raw(), $class.as_raw()) };
        assert!(is_assignable, "Type {} is not a valid (assignable) alias for type {}", stringify!($AliasType), stringify!($Type));
    }};
}

