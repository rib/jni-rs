macro_rules! _impl_api {
    ( $all_props:tt, $ApiTy:ident, $Type:ident, $Class:literal ) => {
        //compile_error! { concat!("API type: ", stringify!($ApiTy), ", Type: ", stringify!($Type), ", Class: ", $Class) }

        struct $ApiTy {
            class: Global<JClass>,
        }
        impl $ApiTy {
            pub fn get(
                env: &Env,
                loader_context: &crate::refs::LoaderContext,
            ) -> crate::errors::Result<&'static Self> {
                static API: once_cell::sync::OnceCell<$ApiTy> = once_cell::sync::OnceCell::new();
                API.get_or_try_init(|| {
                    env.with_local_frame(4, |env| {
                        let class = loader_context
                            .load_class_for_type::<$Type>(false, env)
                            .unwrap();
                        Ok($ApiTy {
                            class: env.new_global_ref(class.as_ref())?,
                        })
                    })
                })
            }
        }
        unsafe impl Send for $ApiTy {}
        unsafe impl Sync for $ApiTy {}
    };
}

