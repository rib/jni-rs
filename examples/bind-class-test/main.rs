macro_rules! _bind_class_with_props_and_api {
    ( $all_props:tt, $ApiTy:ident, $Type:ident, $Class:literal ) => {
        // First, validate we have required properties
        //_ensure_prop!( [ $($props)* ]);

        //compile_error! { concat!(stringify!($( $prop  $value  ),*)) }
        //_foreach! { for_impl, [ $($props)* ], $Type, $Class }

        //_foreach! { for_api, $all_props, _impl_api, $Type, $Class }

        // Start to gather the API struct name, constructors, methods and fields before emitting the API struct
        //_with_api_else! { $all_props, _receive_api_type_then_gather_constructors, [< $Type API >], $Type, $Class }
        _with_priv! { $all_props, _receive_priv_then_gather_constructors, $Type, $Class, $ApiTy }

        #[doc = concat!(r#"A `"#, $Class, r#"` wrapper that is tied to a JNI local reference frame.

See the [`JObject`] documentation for more information about reference
wrappers, how to cast them, and local reference frame lifetimes.

[`JObject`]: $crate::objects::JObject
"#)]
        #[repr(transparent)]
        #[derive(Debug, Default)]
        pub struct $Type<'local>($crate::objects::JObject<'local>);

        impl<'local> AsRef<$Type<'local>> for $Type<'local> {
            #[inline]
            fn as_ref(&self) -> &$Type<'local> {
                self
            }
        }
        impl<'local> AsRef<$crate::objects::JObject<'local>> for $Type<'local> {
            #[inline]
            fn as_ref(&self) -> &$crate::objects::JObject<'local> {
                self
            }
        }
        impl<'local> ::std::ops::Deref for $Type<'local> {
            type Target = $crate::objects::JObject<'local>;
            #[inline]
            fn deref(&self) -> &Self::Target {
                &self.0
            }
        }
        impl<'local> From<$Type<'local>> for $crate::objects::JObject<'local> {
            #[inline]
            fn from(other: $Type<'local>) -> $crate::objects::JObject<'local> {
                other.0
            }
        }

        _foreach! { _select_as, $all_props, _emit_alias_from_impls, $Type }

        // Minimal Reference impl so we can call as_raw() in the harness
        unsafe impl<'local> $crate::refs::Reference for $Type<'local> {
            type Kind<'env> = $Type<'env>;
            type GlobalKind = $Type<'static>;

            #[inline]
            fn as_raw(&self) -> $crate::sys::jobject {
                self.0.as_raw()
            }

            #[inline]
            fn class_name() -> ::std::borrow::Cow<'static, $crate::strings::JNIStr> {
                const CLASS_NAME: &$crate::strings::JNIStr = $crate::strings::JNIStr::from_cstr(
                    match ::std::ffi::CStr::from_bytes_with_nul(concat!($Class, "\0").as_bytes()) {
                        Ok(cstr) => cstr,
                        Err(_) => panic!("Class name is not a valid C string"),
                    },
                );
                ::std::borrow::Cow::Borrowed(CLASS_NAME)
            }

            #[inline]
            fn lookup_class<'caller>(
                env: &$crate::Env<'_>,
                loader_context: &$crate::refs::LoaderContext,
            ) -> $crate::errors::Result<
                impl ::std::ops::Deref<
                        Target = $crate::refs::Global<$crate::objects::JClass<'static>>,
                    > + 'caller,
            > {
                let api = $ApiTy::get(env, &loader_context)?;
                Ok(&api.class)
            }

            #[inline]
            unsafe fn kind_from_raw<'env>(local_ref: $crate::sys::jobject) -> Self::Kind<'env> {
                $Type($crate::objects::JObject::kind_from_raw(local_ref))
            }

            #[inline]
            unsafe fn global_kind_from_raw(global_ref: $crate::sys::jobject) -> Self::GlobalKind {
                $Type($crate::objects::JObject::global_kind_from_raw(global_ref))
            }
        }

        impl<'local> $Type<'local> {
            _with_raw_else! { $all_props, _emit_base_methods, jobject, $Type, $Class }

            _foreach! { _select_as, $all_props, _emit_alias_as_methods, $Type }

            _foreach! { _select_constructors, $all_props, _impl_constructors, $Type, $ApiTy }
            _foreach! { _select_static_methods, $all_props, _impl_static_methods, $Type, $ApiTy }
            _foreach! { _select_methods, $all_props, _impl_methods, $Type, $ApiTy }
            _foreach! { _select_static_fields, $all_props, _impl_static_fields, $Type, $ApiTy }
            _foreach! { _select_fields, $all_props, _impl_fields, $Type, $ApiTy }
        }
    };
}

