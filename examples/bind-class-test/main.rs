#[macro_export]
macro_rules! _emit_api {
    ( $all_props:tt, $Type:ident, $Class:literal, $ApiTy:ident, $PrivTy:ident,
        { $( $constructor_rname:ident = { $($constructor_desc:tt)* } ),* $(,)? },
        { $( $static_method_rname:ident = { $($static_method_desc:tt)* } ),* $(,)? },
        { $( $method_rname:ident = { $($method_desc:tt)* } ),* $(,)? },
        $static_native_methods:tt,
        $native_methods:tt,
        { $( $static_field_rname:ident = { $($static_field_desc:tt)* } ),* $(,)? },
        { $( $field_rname:ident = { $($field_desc:tt)* } ),* $(,)? }
     ) => {
        //compile_error! { concat!("API type: ", stringify!($ApiTy), ", Type: ", stringify!($Type), ", Class: ", $Class, ", Private: ", stringify!($PrivTy)) }

        _with_native_trait_state! { $all_props, _emit_native_methods_trait, $Type, $static_native_methods, $native_methods }

        $crate::__pastey! {
            struct $ApiTy {
                class: $crate::refs::Global<$crate::objects::JClass<'static>>,
                private: $PrivTy,
                $( [<$constructor_rname _method_id>]: $crate::ids::JMethodID, )*
                $( [<$static_method_rname _method_id>]: $crate::ids::JStaticMethodID, )*
                $( [<$method_rname _method_id>]: $crate::ids::JMethodID, )*
                $( [<$field_rname _field_id>]: $crate::ids::JFieldID, )*
                $( [<$static_field_rname _field_id>]: $crate::ids::JStaticFieldID, )*
            }

            impl $ApiTy {
                #[allow(unused)]
                fn _load_class_wrapper<'env_local, F>(env: &mut $crate::Env<'env_local>, loader: &$crate::refs::LoaderContext, initialize: bool, load_class: F) -> $crate::errors::Result<JClass<'env_local>>
                where
                    F: FnOnce(&mut $crate::Env<'env_local>, &$crate::refs::LoaderContext, bool) -> $crate::errors::Result<JClass<'env_local>>,
                {
                    load_class(env, loader, initialize)
                }
                #[allow(unused)]
                fn _init_priv_wrapper<'env_local, F>(env: &mut $crate::Env<'env_local>, loader: &$crate::refs::LoaderContext, class: &JClass, init_priv: F) -> $crate::errors::Result<$PrivTy>
                where
                    F: FnOnce(&mut $crate::Env<'env_local>, &$crate::refs::LoaderContext, &JClass) -> $crate::errors::Result<$PrivTy>,
                {
                    init_priv(env, loader, class)
                }

                pub fn get(env: &Env, loader: &$crate::refs::LoaderContext) -> $crate::errors::Result<&'static Self> {
                    static CELL: once_cell::sync::OnceCell<$ApiTy> = once_cell::sync::OnceCell::new();
                    CELL.get_or_try_init(|| {
                        env.with_local_frame(4, |env| {
                            // load the class without asking to initialize it, in case the initialization might try to call native methods
                            // that are not yet registered
                            //
                            // The class will, indirectly be be initialized later after registering native methods, when method IDs are looked up
                            let class: JClass = _with_impl_closures! {$all_props, _emit_load_class_closure, $Type, env, loader, false };

                            // gather native_type, native_type_impl and native_error_policy before emitting native method registration
                            _with_native_trait_state! { $all_props, _emit_register_native_methods, $Type, $static_native_methods, $native_methods, env, &class }

                            let private: $PrivTy = _with_impl_closures! {$all_props, _emit_init_priv_closure, $Type, env, loader, &class };

                            // Assert that aliases are valid
                            $crate::_foreach! { _select_as, $all_props, _emit_alias_assignable_checks, $Type, &class, env, loader }

                            let api = Self {
                                class: env.new_global_ref(&class)?,
                                private,
                                $(
                                    [<$constructor_rname _method_id>]: $crate::__drt__parse_method_body!{@constructor __drt_emit_api_method_id_init, $constructor_rname = { $($constructor_desc)+ }, env, &class },
                                )*
                                $(
                                    [<$static_method_rname _method_id>]: $crate::__drt__parse_method_body!{@static_method __drt_emit_api_static_method_id_init, $static_method_rname = { $($static_method_desc)+ }, env, &class },
                                )*
                                $(
                                    [<$method_rname _method_id>]: $crate::__drt__parse_method_body!{@method __drt_emit_api_method_id_init, $method_rname = { $($method_desc)+ }, env, &class },
                                )*
                                $(
                                    [<$field_rname _field_id>]: $crate::__drt__parse_field_body!{@field __drt_emit_api_field_id_init, $field_rname = { $($field_desc)+ }, env, &class },
                                )*
                                $(
                                    [<$static_field_rname _field_id>]: $crate::__drt__parse_field_body!{@static_field __drt_emit_api_static_field_id_init, $static_field_rname = { $($static_field_desc)+ }, env, &class },
                                )*
                            };
                            Ok(api)
                        })
                    })
                }

                _with_native_trait_state! { $all_props, _emit_native_method_wrappers, $Type, $static_native_methods, $native_methods, $Class }
            }

            unsafe impl Send for $ApiTy {}
            unsafe impl Sync for $ApiTy {}

            _with_native_trait_state! { $all_props, _emit_native_method_exports, $Type, $static_native_methods, $native_methods, $Class, $ApiTy }
        }
    };
}

