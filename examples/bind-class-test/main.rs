#[macro_export]
macro_rules! _emit_register_native_methods {
    (
        $all_props:tt,
        $Type:ident,
        $native_trait:ident,
        $native_trait_impl:ident,
        $default_error_policy:path,
        { $( $static_native_method_rname:ident = { $($static_native_method_desc:tt)* } ),* $(,)? },
        { $( $native_method_rname:ident = { $($native_method_desc:tt)* } ),* $(,)? },
        $env:expr,
        $class:expr
    ) => {
        //compile_error! { concat!("Native trait: ", stringify!($native_trait), ", impl: ", stringify!($native_trait_impl), ", error policy: ", stringify!($default_error_policy)) }

        let static_native_methods = &[
            $(
                $crate::__drt__parse_method_body!{@static_native_method __drt__emit_api_native_method_decl, $static_native_method_rname = { $($static_native_method_desc)+ }, $default_error_policy, $Type },
            )*
        ];
        if !static_native_methods.is_empty() {
            unsafe { $env.register_native_methods($class, static_native_methods)?; }
        }
        let native_methods = &[
            $(
                $crate::__drt__parse_method_body!{@native_method __drt__emit_api_native_method_decl, $native_method_rname = { $($native_method_desc)+ }, $default_error_policy, $Type },
            )*
        ];
        if !native_methods.is_empty() {
            unsafe { $env.register_native_methods($class, native_methods)?; }
        }
    };
}

